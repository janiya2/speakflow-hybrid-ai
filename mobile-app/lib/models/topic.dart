class TopicModel {
  final String id;
  final String title;
  final String language;
  final String level;
  final String category;
  final String subCategory;
  final String icon;
  final String scenario;
  final String starterPrompt;
  final List<String> starterQuestions;
  final bool isActive;

  TopicModel({
    required this.id,
    required this.title,
    required this.language,
    required this.level,
    this.category = 'Daily Life',
    this.subCategory = 'General',
    required this.icon,
    required this.scenario,
    required this.starterPrompt,
    required this.starterQuestions,
    this.isActive = true,
  });

  factory TopicModel.fromFirestore(Map<String, dynamic> data, String id) {
    return TopicModel(
      id: id,
      title: data['title'] ?? '',
      language: data['language'] ?? 'English',
      level: data['level'] ?? 'Beginner',
      category: data['category'] ?? 'Daily Life',
      subCategory: data['subCategory'] ?? 'General',
      icon: data['icon'] ?? '💬',
      scenario: data['scenario'] ?? '',
      starterPrompt: data['starterPrompt'] ?? '',
      starterQuestions: List<String>.from(data['starterQuestions'] ?? []),
      isActive: data['isActive'] ?? true,
    );
  }

  Map<String, dynamic> toMap() {
    return {
      'title': title,
      'language': language,
      'level': level,
      'category': category,
      'subCategory': subCategory,
      'icon': icon,
      'scenario': scenario,
      'starterPrompt': starterPrompt,
      'starterQuestions': starterQuestions,
      'isActive': isActive,
    };
  }
}

